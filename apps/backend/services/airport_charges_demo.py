# 2. EXPOSURE CALCULATION ENGINE -- resolves each formula to a real SEK number
# ---------------------------------------------------------------------------
 
def compute_penalty_exposure(kpi_code: str, **inputs) -> dict:
    """Resolve a Paragraph 13 penalty to a concrete SEK exposure given raw inputs.
    Returns {"exposure_sek": float|None, "breach": bool, "detail": str}.
    """
    if kpi_code == "SGHA-13.1-TURNAROUND-DELAY":
        delay_min = inputs["delay_minutes"]
        breach = delay_min > 0
        exposure = min(500 * math.ceil(delay_min / 15), 10000) if breach else 0
        return {"exposure_sek": exposure, "breach": breach,
                "detail": f"{delay_min} min delay -> {math.ceil(delay_min/15) if breach else 0} x 500, capped 10000"}
 
    if kpi_code == "SGHA-13.2-FAILURE-TO-PROVIDE":
        occurred = inputs["occurrence"]
        turnaround_charge = inputs.get("applicable_turnaround_charge", 0)
        exposure = (turnaround_charge * 1.00 + 3000) if occurred else 0
        return {"exposure_sek": exposure, "breach": occurred,
                "detail": f"100% of turnaround charge ({turnaround_charge}) + 3000 fixed"}
 
    if kpi_code == "SGHA-13.3-BAGGAGE-CARGO-MISHANDLING":
        items = inputs["affected_item_count"]
        exposure = 750 * items
        return {"exposure_sek": exposure, "breach": items > 0, "detail": f"{items} item(s) x 750"}
 
    if kpi_code == "SGHA-13.4-DEICING-FAILURE":
        minutes = inputs.get("minutes_to_commence")
        caused_delay = inputs.get("caused_departure_delay", False)
        breach = (minutes is not None and minutes > 20) or caused_delay
        exposure = 2500 if breach else 0
        return {"exposure_sek": exposure, "breach": breach,
                "detail": f"minutes_to_commence={minutes}, caused_departure_delay={caused_delay}"}
 
    if kpi_code == "SGHA-13.5-REFUELLING-DELAY":
        minutes_before = inputs["minutes_before_departure_completed"]
        breach = minutes_before < 15
        exposure = 1200 if breach else 0
        return {"exposure_sek": exposure, "breach": breach,
                "detail": f"completed {minutes_before} min before departure (threshold 15)"}
 
    if kpi_code == "SGHA-13.6-SAFETY-COMPLIANCE-BREACH":
        incidents = inputs["incident_count"]
        exposure = 15000 * incidents
        return {"exposure_sek": exposure, "breach": incidents > 0, "detail": f"{incidents} Para 9 incident(s) x 15000"}
 
    if kpi_code == "SGHA-13.7-MONTHLY-ON-TIME-SLA":
        on_time_pct = inputs["on_time_pct"]
        monthly_handling_charges = inputs["monthly_handling_charges"]
        points_below = max(0, math.floor(95 - on_time_pct))
        pct_credit = min(0.02 * points_below, 0.20)
        exposure = pct_credit * monthly_handling_charges
        return {"exposure_sek": round(exposure, 2), "breach": points_below > 0,
                "detail": f"{on_time_pct}% on-time -> {points_below} pts below 95, {pct_credit*100:.0f}% of {monthly_handling_charges} SEK monthly handling charges"}
 
    raise ValueError(f"Unknown Paragraph 13 KPI code: {kpi_code}")
 
 
